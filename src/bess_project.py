import pandas as pd
import numpy as np

# ==========================================
# 1. ΦΟΡΤΩΣΗ ΔΕΔΟΜΕΝΩΝ
# ==========================================
#Φόρτωση τιμών
df_prices = pd.read_csv('Price per hour.csv', sep=';', decimal=',')
#Φόρτωση παραγωγής
df_production = pd.read_csv('Energy per hour.csv', sep=';', decimal=',', header=None)

#Καθάρισμα πίνακα παραγωγής
df_production.columns = ['PVsyst_Time', 'Energy_W']
df_production['Energy_MW'] = df_production['Energy_W'] / 1000000
df_production['Datetime'] = pd.date_range(start='2025-01-01 00:00', periods=8760, freq='h')
df_production.set_index('Datetime', inplace=True)

#Καθάρισμα πίνακα τιμών
df_prices.columns = df_prices.columns.str.strip()
time_col = df_prices.columns[0]
price_col = df_prices.columns[1]

df_prices[price_col] = pd.to_numeric(df_prices[price_col].astype(str).str.replace(',', '.'), errors='coerce')
df_prices['Datetime'] = df_prices[time_col].astype(str).str.split(' - ').str[0].str.strip().str[:19]
df_prices['Datetime'] = pd.to_datetime(df_prices['Datetime'], format='%d/%m/%Y %H:%M:%S', errors='coerce')
df_prices.set_index('Datetime', inplace=True)

df_prices_hourly = df_prices.resample('h').mean(numeric_only=True)
df_final = pd.concat([df_production['Energy_MW'], df_prices_hourly[price_col]], axis=1)
df_final.columns = ['Solar_MW', 'Price_EUR_MWh']

# Καθαρίζουμε τα κενά (NaNs)
df_final['Solar_MW'] = df_final['Solar_MW'].fillna(0) # Αν λείπει παραγωγή = 0
df_final['Price_EUR_MWh'] = df_final['Price_EUR_MWh'].ffill().bfill() # Forward fill στις τιμές


# =======================================================
# 2. ΠΡΟΣΟΜΟΙΩΣΗ ΜΠΑΤΑΡΙΑΣ
# =======================================================
BESS_CAPACITY = 3.84   # MWh
BESS_POWER = 2.0   # MW
BESS_AUX_MW = 0.00385 # H ιδιοκατανάλωση της μπαταρίας (3.85 kW)από το PVsyst

grid_static = []
grid_dynamic = []

prices = df_final['Price_EUR_MWh'].values
solar = df_final['Solar_MW'].values

# Α. ΣΤΑΤΙΚΟΣ ΑΛΓΟΡΙΘΜΟΣ (40€ - 120€)
CHARGE_PRICE = 40.0
DISCHARGE_PRICE = 120.0
battery_static = 0.0

for i in range(len(prices)):
    p, s = prices[i], solar[i]
    charge, discharge = 0.0, 0.0

    if p < CHARGE_PRICE and battery_static < BESS_CAPACITY:
        charge = min(BESS_POWER, BESS_CAPACITY - battery_static, s)
        battery_static += charge
    elif p > DISCHARGE_PRICE and battery_static > 0:
        discharge = min(BESS_POWER, battery_static)
        battery_static -= discharge

    net_power = s - charge + discharge - BESS_AUX_MW
    grid_static.append(min(3.5, net_power))

# Β. ΔΥΝΑΜΙΚΟΣ ΑΛΓΟΡΙΘΜΟΣ
df_final['Date'] = df_final.index.date
battery_dynamic = 0.0

for date, daily_data in df_final.groupby('Date'):
    cheapest_threshold = daily_data['Price_EUR_MWh'].nsmallest(2).max()
    expensive_threshold = daily_data['Price_EUR_MWh'].nlargest(2).min()

    for idx, row in daily_data.iterrows():
        p, s = row['Price_EUR_MWh'], row['Solar_MW']
        charge, discharge = 0.0, 0.0

        if p <= cheapest_threshold and battery_dynamic < BESS_CAPACITY:
            charge = min(BESS_POWER, BESS_CAPACITY - battery_dynamic, s)
            battery_dynamic += charge
        elif p >= expensive_threshold and battery_dynamic > 0:
            # Υπολογίζουμε πόσος χώρος υπάρχει στο δίκτυο μέχρι τα 3.5 MW
            available_grid_capacity = max(0.0, 3.5 - s)

            # Η εκφόρτιση περιορίζεται από τη δύναμη του Inverter (2MW),
            #το ρεύμα που έχει μέσα η μπαταρία και τον ελεύθερο χώρο του δικτύου!
            discharge = min(BESS_POWER, battery_dynamic, available_grid_capacity)
            battery_dynamic -= discharge

        net_power = s - charge + discharge - BESS_AUX_MW
        grid_dynamic.append(min(3.5, net_power))

# =======================================================
# 3. ΟΙΚΟΝΟΜΙΚΑ ΑΠΟΤΕΛΕΣΜΑΤΑ
# =======================================================
rev_no_bess = (df_final['Solar_MW'].clip(upper=3.5) * df_final['Price_EUR_MWh']).sum()
rev_static = (np.array(grid_static) * prices).sum()
rev_dynamic = (np.array(grid_dynamic) * prices).sum()

print("📊 ΟΙΚΟΝΟΜΙΚΗ ΑΝΑΛΥΣΗ (PV 5MWp | BESS 3.84 MWh)")
print("=" * 75)
print(f"1. Απλό Πάρκο (Χωρίς Μπαταρία): {rev_no_bess:,.0f} €")
print(f"2. Μπαταρία με Στατικό Αλγόριθμο (40€-120€): {rev_static:,.0f} €  (+ {rev_static - rev_no_bess:,.0f} € έξτρα)")
print(f"3. Μπαταρία με Δυναμικό Αλγόριθμο (Smart): {rev_dynamic:,.0f} €  (+ {rev_dynamic - rev_no_bess:,.0f} € έξτρα)")
print("=" * 75)
print(f"🧠 Αξία Ανάλυσης Δεδομένων (Διαφορά Στατικού-Δυναμικού): +{rev_dynamic - rev_static:,.0f} € !!!")

