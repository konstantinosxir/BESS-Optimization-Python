import pulp
import pandas as pd
import numpy as np

print("=" * 60)
print("Εγκαθιστούμε τη βιβλιοθήκη PuLP και ξεκινάμε τη βελτιστοποίηση")
print("=" * 60)

# Βασικές παράμετροι
BESS_CAPACITY = 3.84
BESS_POWER = 2.0
BESS_AUX_MW = 0.00385
T = len(df_final)  # 8760 ώρες

prices = df_final['Price_EUR_MWh'].values
solar = df_final['Solar_MW'].values

# 1. Ορισμός Προβλήματος: Μεγιστοποίηση εσόδων (LpMaximize)
prob = pulp.LpProblem("BESS_Optimal_Arbitrage", pulp.LpMaximize)

# 2. Ορισμός Μεταβλητών Απόφασης
charge = pulp.LpVariable.dicts("Charge", range(T), lowBound=0, upBound=BESS_POWER)
discharge = pulp.LpVariable.dicts("Discharge", range(T), lowBound=0, upBound=BESS_POWER)
soc = pulp.LpVariable.dicts("SoC", range(T), lowBound=0, upBound=BESS_CAPACITY)
# Η μεταβλητή για το ρεύμα που "κόβει" ο Inverter εξαιτίας
# του ορίου έγυχσης στο δίκτυο
curtail = pulp.LpVariable.dicts("Curtail", range(T), lowBound=0)

# 3. Αντικειμενική Συνάρτηση: Συνολικό ετήσιο κέρδος
# Έσοδα = (Ήλιος - Περικοπή - Φόρτιση + Εκφόρτιση - Ιδιοκατανάλωση) * Τιμή
prob += pulp.lpSum([(solar[t] - curtail[t] - charge[t] + discharge[t] - BESS_AUX_MW) * prices[t] for t in range(T)])

# 4. Περιορισμοί
for t in range(T):
    # Περιορισμός Α: Η φόρτιση και η περικοπή δεν μπορούν να ξεπερνούν την διαθέσιμη ενέργεια από τον ήλιο
    prob += charge[t] + curtail[t] <= solar[t], f"Solar_Balance_{t}"

    # Περιορισμός Β: Battery State of Charge
    if t == 0:
        # Την 1η ώρα του έτους: Το SoC είναι απλά Φόρτιση - Εκφόρτιση
        prob += soc[t] == charge[t] - discharge[t], f"SoC_Balance_{t}"
    else:
        # Τις υπόλοιπες ώρες: Νέο SoC = Προηγούμενο SoC + Φόρτιση - Εκφόρτιση
        prob += soc[t] == soc[t-1] + charge[t] - discharge[t], f"SoC_Balance_{t}"

    # Περιορισμός Γ: Grid Power Limit 3.5 MW
    prob += (solar[t] - curtail[t] - charge[t] + discharge[t] - BESS_AUX_MW) <= 3.5, f"Grid_Limit_{t}"

# 5. Λύση
print("Ο αλγόριθμος λύνει την εξίσωση.")
prob.solve()

# 6. Εξαγωγή των βέλτιστων αποτελεσμάτων
optimal_grid = []
for t in range(T):
    c_val = charge[t].varValue
    d_val = discharge[t].varValue
    curt_val = curtail[t].varValue
    optimal_grid.append(solar[t] - curt_val - c_val + d_val - BESS_AUX_MW)

rev_no_bess = (df_final['Solar_MW'].clip(upper=3.5) * df_final['Price_EUR_MWh']).sum()
rev_optimal = (np.array(optimal_grid) * prices).sum()

print("\n📊 ΑΠΟΤΕΛΕΣΜΑΤΑ ΓΡΑΜΜΙΚΟΥ ΠΡΟΓΡΑΜΜΑΤΙΣΜΟΥ (Absolute Optimal)")
print("=" * 70)
print(f"Κατάσταση Επίλυσης:          {pulp.LpStatus[prob.status]}")
print(f"1. Απλό Πάρκο (No BESS):     {rev_no_bess:,.0f} €")
print(f"2. Μαθηματικό Μέγιστο (LP):  {rev_optimal:,.0f} €  (+ {rev_optimal - rev_no_bess:,.0f} € έξτρα)")
print("=" * 70)